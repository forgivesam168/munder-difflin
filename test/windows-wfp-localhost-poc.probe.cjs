function canonicalCommandBytes(command) {
  assert.equal(typeof command, 'string');
  assert.ok(command.length > 0);
  assert.doesNotMatch(command, /[\r\n]/, 'command must be a single logical line');
  return Buffer.from(command + '\r\n', 'utf8');
}

// The command file is the canonical handoff artifact: UTF-8 without BOM, exactly one
// terminal CRLF. Bytes are written exclusively, reread from disk, and only a byte- and
// hash-identical reread may be reported as verified.
function writeCommandFile(file, command) {
  const expected = canonicalCommandBytes(command);
  fs.writeFileSync(file, expected, { flag: 'wx' });
  const reread = fs.readFileSync(file);
  assert.equal(reread.length, expected.length, 'command file byte length must equal generated bytes');
  assert.equal(reread.compare(expected), 0, 'command file bytes must equal generated bytes');
  const sha256 = digest(reread), expectedSha256 = digest(expected);
  assert.equal(sha256, expectedSha256, 'command file hash must equal generated hash');
  assert.equal(reread.subarray(0, 3).equals(Buffer.from([0xEF, 0xBB, 0xBF])), false, 'command file must not carry a BOM');
  assert.equal(reread.subarray(-2).equals(Buffer.from('\r\n', 'utf8')), true, 'command file must end with CRLF');
  return { path: file, encoding: commandFileEncoding, newline: commandFileNewline, bom: false, byteLength: reread.length, sha256 };
}

