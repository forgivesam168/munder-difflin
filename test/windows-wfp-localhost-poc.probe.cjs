  const command = `& ${quote(powershell)} -NoLogo -NoProfile -NonInteractive -EncodedCommand ${Buffer.from(liveScript, 'utf16le').toString('base64')}`;
  return { proofId, previousCommand: 'INVALID_DO_NOT_EXECUTE: prior repository-direct elevation command is superseded', protectedStage: stage, stageAclSddl: sddl, stagedController, stagedProbe, stagedControllerSha256: controllerSha256, stagedProbeSha256: probeSha256, stagedReceipt, liveReceipt, exposureTemp, receiptHashOutput: 'WFP_RECEIPT_SHA256=<lowercase SHA256 of staged receipt bytes before exposure>', humanRunElevatedPowerShellCommand: command, decodedPowerShell: liveScript };
